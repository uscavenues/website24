/**
 * Generates apps-script/Setup.gs from the seed TSVs.
 *
 * Uploading a workbook to Drive turned out to be unreliable (the connector
 * refused xlsx->Sheets conversion, and an unconverted .xlsx would not open),
 * so the sheet is built by the Apps Script instead — which the user is pasting
 * in anyway, and which can create tabs and validation natively.
 *
 *   node scripts/make-setup-gs.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TABS = ["settings", "team", "mentors", "alumni", "clients", "majors", "faq"];

const rows = (t) =>
  readFileSync(join(ROOT, "apps-script/seed", `${t}.tsv`), "utf8")
    .replace(/\n$/, "")
    .split("\n")
    .map((l) => l.split("\t"));

const js = (v) => JSON.stringify(v);

let out = `/**
 * One-time sheet builder. Menu: Avenues > Set up sheet (first time).
 *
 * Creates the seven tabs, fills them with what is currently live on the site,
 * and applies the header formatting and dropdowns. Running it again REPLACES
 * the contents of those tabs, so it is safe to re-run before anyone has made
 * edits and destructive afterwards — it asks first.
 *
 * Generated by scripts/make-setup-gs.mjs from apps-script/seed/*.tsv.
 * Do not hand-edit; regenerate instead.
 */

var SEED = {
`;

for (const t of TABS) {
  const r = rows(t);
  out += `  ${t}: [\n${r.map((row) => `    ${js(row)}`).join(",\n")}\n  ],\n`;
}

out += `};

var TAB_ORDER = ${js(TABS)};

/** Column widths, so the sheet is readable the moment it opens. */
var WIDTHS = {
  settings: [220, 520],
  team: [110, 170, 230, 130, 400],
  mentors: [220, 230],
  alumni: [220, 260, 320],
  clients: [190, 230, 320],
  majors: [260],
  faq: [400, 700],
};

function setUpSheet() {
  var ui = SpreadsheetApp.getUi();
  var ss = SpreadsheetApp.getActive();

  var existing = TAB_ORDER.filter(function (t) {
    return ss.getSheetByName(t) !== null;
  });
  if (existing.length) {
    var answer = ui.alert(
      'Replace existing tabs?',
      'This will overwrite: ' + existing.join(', ') +
        '\\n\\nAny edits in those tabs are lost. Continue?',
      ui.ButtonSet.YES_NO
    );
    if (answer !== ui.Button.YES) return;
  }

  TAB_ORDER.forEach(function (name) {
    var sheet = ss.getSheetByName(name);
    if (sheet) {
      sheet.clear();
      sheet.clearDataValidations();
    } else {
      sheet = ss.insertSheet(name);
    }
    var data = SEED[name];
    sheet.getRange(1, 1, data.length, data[0].length).setValues(data);

    // header row: dark, bold, frozen so it cannot scroll away
    var header = sheet.getRange(1, 1, 1, data[0].length);
    header.setFontWeight('bold').setFontColor('#ffffff').setBackground('#1f2937');
    sheet.setFrozenRows(1);

    (WIDTHS[name] || []).forEach(function (w, i) {
      sheet.setColumnWidth(i + 1, w);
    });
    if (name === 'faq') {
      sheet.getRange(2, 1, Math.max(sheet.getMaxRows() - 1, 1), 2).setWrap(true);
    }
  });

  // section dropdown — a typo here silently drops someone off the site
  var team = ss.getSheetByName('team');
  team
    .getRange(2, 1, Math.max(team.getMaxRows() - 1, 1), 1)
    .setDataValidation(
      SpreadsheetApp.newDataValidation()
        .requireValueInList(['executive', 'directors', 'associates'], true)
        .setAllowInvalid(false)
        .setHelpText('Must be executive, directors, or associates.')
        .build()
    );

  // applications_open must be a real boolean
  var settings = ss.getSheetByName('settings');
  var keys = settings.getRange(1, 1, settings.getLastRow(), 1).getValues();
  for (var i = 0; i < keys.length; i++) {
    if (String(keys[i][0]).trim() === 'applications_open') {
      settings
        .getRange(i + 1, 2)
        .setDataValidation(
          SpreadsheetApp.newDataValidation()
            .requireValueInList(['TRUE', 'FALSE'], true)
            .setAllowInvalid(false)
            .build()
        );
    }
  }

  // drop Google's default empty "Sheet1" if it is still lying around
  var leftover = ss.getSheetByName('Sheet1');
  if (leftover && ss.getSheets().length > 1) ss.deleteSheet(leftover);

  TAB_ORDER.forEach(function (name, i) {
    ss.setActiveSheet(ss.getSheetByName(name));
    ss.moveActiveSheet(i + 1);
  });
  ss.setActiveSheet(ss.getSheetByName('team'));

  ui.alert(
    'Sheet ready',
    'Created ' + TAB_ORDER.length + ' tabs with the content currently on the site.\\n\\n' +
      'Next: add your GitHub token under Project Settings > Script Properties as ' +
      'GITHUB_TOKEN, then run Avenues > Check for problems.',
    ui.ButtonSet.OK
  );
}
`;

writeFileSync(join(ROOT, "apps-script/Setup.gs"), out);
const counts = TABS.map((t) => `${t}=${rows(t).length - 1}`).join(" ");
console.log("wrote apps-script/Setup.gs");
console.log("  seeded rows:", counts);
